#!/usr/bin/env node
// Copies Miden's verified token lists (github.com/0xMiden/token-list) and their
// logos into the app at one commit, and writes the logo imports. Run from
// bin/coordinator-frontend:
//
//   node scripts/update-token-list.mjs <token-list commit sha>
//
// The app ships this snapshot, as the Miden Wallet does, so it needs no
// network call and no change to its security policy.
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const NETWORKS = ['mainnet', 'testnet'];
const REPO = 'https://raw.githubusercontent.com/0xMiden/token-list';
const ref = process.argv[2];
if (!/^[0-9a-f]{40}$/.test(ref ?? '')) {
  console.error('Usage: node scripts/update-token-list.mjs <full token-list commit sha>');
  process.exit(1);
}

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'config', 'tokenList');
const logoDir = join(out, 'logos');
await rm(logoDir, { recursive: true, force: true });
await mkdir(logoDir, { recursive: true });

async function fetchOk(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response;
}

const logos = [];
for (const network of NETWORKS) {
  const list = await (await fetchOk(`${REPO}/${ref}/${network}.json`)).json();
  if (!Array.isArray(list.tokens)) throw new Error(`${network}.json has no tokens`);
  for (const token of list.tokens) {
    if (token.network !== network) throw new Error(`${token.faucetId} is listed for ${token.network} in ${network}.json`);
    if (!token.logoURI) continue;
    const expected = `${REPO}/main/logos/${token.faucetId}/logo.png`;
    if (token.logoURI !== expected) throw new Error(`${token.faucetId}: unexpected logoURI ${token.logoURI}`);
    const png = Buffer.from(await (await fetchOk(`${REPO}/${ref}/logos/${token.faucetId}/logo.png`)).arrayBuffer());
    if (png.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error(`${token.faucetId}: logo is not a PNG`);
    await writeFile(join(logoDir, `${token.faucetId}.png`), png);
    logos.push(token.faucetId);
  }
  await writeFile(join(out, `${network}.json`), `${JSON.stringify(list, null, 2)}\n`);
}

const lines = [
  `// Generated by scripts/update-token-list.mjs from 0xMiden/token-list at ${ref}. Do not edit.`,
  "import type { StaticImageData } from 'next/image';",
  ...logos.map((id, i) => `import logo${i} from './logos/${id}.png';`),
  '',
  `export const TOKEN_LIST_COMMIT = '${ref}';`,
  '',
  '/** Each listed token\'s logo, by faucet address. */',
  'export const TOKEN_LOGOS: Record<string, StaticImageData> = {',
  ...logos.map((id, i) => `  '${id}': logo${i},`),
  '};',
  '',
];
await writeFile(join(out, 'logos.ts'), lines.join('\n'));
console.log(`token list ${ref.slice(0, 12)}: ${NETWORKS.join(', ')}, ${logos.length} logos`);
